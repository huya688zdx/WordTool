class I18n(QObject):
    """Internationalization manager with language switching signal."""

    language_changed = Signal(str)

    _instance = None
    _current_lang = "zh"

    def __init__(self):
        super().__init__()
        I18n._instance = self

    @classmethod
    def instance(cls):
        if cls._instance is None:
            cls._instance = I18n()
        return cls._instance

    @classmethod
    def get(cls, key: str, **kwargs) -> str:
        text = _translations.get(cls._current_lang, {}).get(
            key, _translations["en"].get(key, key)
        )
        if kwargs:
            text = text.format(**kwargs)
        return text

    @classmethod
    def tr(cls, key: str, **kwargs) -> str:
        """Alias for get()."""
        return cls.get(key, **kwargs)

    @classmethod
    def current_lang(cls) -> str:
        return cls._current_lang

    @classmethod
    def set_language(cls, lang: str):
        if lang in _translations:
            cls._current_lang = lang
            if cls._instance:
                cls._instance.language_changed.emit(lang)

    @classmethod
    def languages(cls):
        return [
            ("en", "English"),
            ("ja", "日本語"),
            ("zh", "中文"),
        ]
